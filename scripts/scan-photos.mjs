// Lists real product/hero photos present in /public so the UI only requests files that exist.
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
const root = "public";
const out = [];
const walk = (d) => { if (!existsSync(d)) return; for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.(jpe?g|png|webp|avif)$/i.test(f)) out.push("/" + relative(root, p).replace(/\\/g, "/")); } };
walk(join(root, "products")); walk(join(root, "hero")); walk(join(root, "logo"));
writeFileSync("src/lib/photo-manifest.ts", `// Generated by scripts/scan-photos.mjs — do not edit.\nexport const PHOTOS = new Set<string>(${JSON.stringify(out, null, 2)});\n`);
console.log(`photo manifest: ${out.length} files`);
